"""Run the unchanged external PT/MeDeT source builder with package-local inputs.

verify performs file checks only; preflight imports and loads frozen assets but
does not train. train runs the original full H=(1,4) protocol in a fresh output.
Only the two H=1 checkpoints are used by Paper3 and compared here. The historical
C1 bank/pi50 selection inputs are verified, not regenerated by this entrypoint.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sys
import sysconfig
import traceback

PACKAGE = Path(__file__).resolve().parent
SOURCE = PACKAGE / 'upstream_source_training/external_source_original'


def read(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def write(path, obj):
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding='utf-8')


def contained(path, root):
    return path == root or path.is_relative_to(root)


def install_read_guard(out):
    roots = [PACKAGE, out, Path(sys.base_prefix).resolve(), Path(sys.prefix).resolve()]
    roots += [Path(sysconfig.get_path(key)).resolve() for key in ('purelib', 'platlib')]
    def audit(event, args):
        if event != 'open' or not args or isinstance(args[0], int):
            return
        raw_path = os.fsdecode(args[0])
        if raw_path.casefold() == os.devnull.casefold():
            return
        path = Path(raw_path).resolve()
        if not any(contained(path, root) for root in roots):
            raise RuntimeError('External file access denied: ' + str(path))
    sys.addaudithook(audit)


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--mode', choices=('verify', 'preflight', 'train'), required=True)
    parser.add_argument('--device', choices=('cpu', 'cuda'), default='cuda')
    parser.add_argument('--safe-mode', choices=('default', 'gru-native', 'gru-cpu'), default='gru-native')
    args = parser.parse_args()
    out = args.output.resolve()
    if out.exists() or contained(out, PACKAGE) or contained(PACKAGE, out):
        raise RuntimeError('Use a new output directory outside the source package')
    out.mkdir(parents=True)
    try:
        collection = read(SOURCE / 'COLLECTION_RECEIPT.json')
        for row in collection['files']:
            path = (SOURCE / row['file']).resolve()
            if not contained(path, SOURCE) or sha(path) != row['sha256']:
                raise RuntimeError('Collected source/input mismatch: ' + row['file'])
            if path.suffix == '.py':
                compile(path.read_bytes(), str(path), 'exec')
        for target in collection['target_models']:
            if sha(PACKAGE / target['paper_checkpoint']) != target['checkpoint_sha256']:
                raise RuntimeError('Frozen target checkpoint changed: ' + target['identity'])
        launch_root = PACKAGE / 'upstream_source_training/external_source_launch_evidence'
        for row in read(launch_root / 'COLLECTION_RECEIPT.json')['files']:
            path = (launch_root / row['file']).resolve()
            if not contained(path, launch_root) or sha(path) != row['sha256']:
                raise RuntimeError('Historical launch evidence changed: ' + row['file'])
        identity = read(launch_root / 'outputs/final_e2e_c23_external_d2904_t2904/preflight/external_baseline_identity.json')
        historical = read(SOURCE / 'outputs/final_e2e_c23_external_d2904_t2904/source_assets/source_assets_manifest.json')
        if identity['decision'] != 'PASS_EXTERNAL_BASELINE_PROTOCOL_FROZEN' or identity['protocol'] != historical['protocol']:
            raise RuntimeError('Original source-training prerequisite is not PASS')
        receipt = dict(mode=args.mode, files_verified=len(collection['files']),
                       python=sys.version, source_models_retrained=False,
                       selection_inputs_regenerated=False, full_package_accepted=False,
                       wrapper_sha256=sha(Path(__file__)))
        if args.mode == 'verify':
            receipt['status'] = 'PASS_STATIC_COLLECTION_ONLY'
            write(out / 'RECEIPT.json', receipt)
            print(json.dumps(receipt), flush=True)
            return
        sys.dont_write_bytecode = True
        # Remove cwd and inherited PYTHONPATH entries before importing legacy
        # top-level cfg/core packages. Keep only the selected interpreter's libs.
        lib_roots = [Path(sys.base_prefix).resolve(), Path(sys.prefix).resolve()]
        sys.path[:] = [str(SOURCE)] + [p for p in sys.path if p and any(
            contained(Path(p).resolve(), root) for root in lib_roots)]
        for key in ('TEMP', 'TMP', 'TORCH_HOME', 'CUDA_CACHE_PATH', 'MPLCONFIGDIR'):
            cache = out / 'cache' / key
            cache.mkdir(parents=True, exist_ok=True)
            os.environ[key] = str(cache)
        os.chdir(out)
        install_read_guard(out)
        import torch
        from external_e2e_c23 import pipeline
        from final_e2e_c23.common import load_frozen_assets
        frozen_manifest = read(SOURCE / 'outputs/final_e2e_c23_external_d2904_t2904/source_assets/source_assets_manifest.json')
        if json.loads(json.dumps(pipeline.config_dict())) != frozen_manifest['protocol']:
            raise RuntimeError('Original source protocol differs from frozen manifest')
        assets = load_frozen_assets(str(SOURCE))
        if assets['hashes'] != frozen_manifest['frozen_asset_hashes']:
            raise RuntimeError('Frozen selection inputs differ from historical manifest')
        del assets
        for name, module in tuple(sys.modules.items()):
            if name.split('.')[0] in {'core', 'cfg', 'final_e2e', 'final_e2e_c23', 'external_e2e_c23'}:
                filename = getattr(module, '__file__', None)
                if filename and not contained(Path(filename).resolve(), SOURCE):
                    raise RuntimeError('Import escaped collected source tree: ' + name)
        receipt.update(torch=str(torch.__version__), device=args.device, safe_mode=args.safe_mode,
                       status='PASS_IMPORT_AND_FROZEN_INPUTS_ONLY')
        write(out / 'PREFLIGHT_RECEIPT.json', receipt)
        if args.mode == 'preflight':
            write(out / 'RECEIPT.json', receipt)
            print(json.dumps(receipt), flush=True)
            return
        generated = out / 'source_assets'
        # The output cannot contain old checkpoints or progress files. All epochs
        # and iterations run through the unchanged historical implementation.
        actual = pipeline.prepare_source_assets(str(SOURCE), str(generated),
                                                args.device, args.safe_mode, smoke=False)
        checks = []
        for target in collection['target_models']:
            new_path = (SOURCE / actual['assets'][target['identity']]['path']).resolve()
            if not contained(new_path, generated):
                raise RuntimeError('New checkpoint is outside fresh output')
            expected = torch.load(PACKAGE / target['paper_checkpoint'], map_location='cpu', weights_only=True)
            current = torch.load(new_path, map_location='cpu', weights_only=True)
            equal = expected.keys() == current.keys() and all(
                expected[k].dtype == current[k].dtype and
                expected[k].shape == current[k].shape and
                torch.equal(expected[k], current[k]) for k in expected)
            checks.append(dict(identity=target['identity'], state_tensors_exact=equal,
                               original_sha256=target['checkpoint_sha256'], new_sha256=sha(new_path)))
        # JSON normalizes the original config's tuples; no numeric tolerances.
        passed = (actual['decision'] == 'PASS_EXTERNAL_SOURCE_ASSETS_FROZEN' and
                  json.loads(json.dumps(actual['protocol'])) == frozen_manifest['protocol'] and
                  actual['fixed_backbones'] == frozen_manifest['fixed_backbones'] and
                  all(row['state_tensors_exact'] for row in checks))
        receipt.update(status='PASS_TWO_EXTERNAL_H1_SOURCE_MODELS' if passed else 'FAIL_SOURCE_COMPARISON',
                       source_models_retrained=True, checks=checks, tolerance=0,
                       h4_models_trained_but_not_compared=True)
        write(out / 'SOURCE_COMPARISON.json', receipt)
        if not passed:
            raise RuntimeError('Source models differ; preserve this run for diagnosis')
        write(out / 'RECEIPT.json', receipt)
        print(json.dumps(receipt), flush=True)
    except BaseException:
        write(out / 'FAILURE.json', dict(status='FAIL', traceback=traceback.format_exc(),
                                       mode=args.mode, full_package_accepted=False))
        raise


if __name__ == '__main__':
    main()
